def database_from_url(url):
    """Parse a DATABASE_URL into Django's DATABASES entry.

    Hand-rolled for the same reason load_dotenv is: one URL shape is not worth
    a dependency, and one less package is one less thing to break on a host we
    do not control.

    Only Postgres. SQLite was dropped deliberately: it is a single file with a
    single writer, and with the ad accounting and the wallet both writing on
    every download, concurrent workers hit "database is locked". Accepting it
    here would let a server run on it by accident and look fine until traffic
    arrived.
    """
    from urllib.parse import unquote, urlparse

    parts = urlparse(url)
    scheme = parts.scheme.replace('+psycopg', '')

    if scheme not in ('postgres', 'postgresql'):
        raise ImproperlyConfigured(
            f'DATABASE_URL must be a postgres:// address, got {parts.scheme!r}.'
        )
    if not parts.path.lstrip('/'):
        raise ImproperlyConfigured('DATABASE_URL has no database name.')

    return {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': unquote(parts.path.lstrip('/')),
        'USER': unquote(parts.username or ''),
        'PASSWORD': unquote(parts.password or ''),
        'HOST': parts.hostname or '',
        'PORT': str(parts.port or ''),
        # One connection reused for ten minutes. Postgres connections are
        # expensive to open and the default of zero opens a fresh one for
        # every request.
        'CONN_MAX_AGE': int(os.environ.get('DB_CONN_MAX_AGE', '600')),
        'CONN_HEALTH_CHECKS': True,
    }


# Postgres everywhere, development included. Running development on a
# different engine than production is how a query that works locally reaches a
# server and fails there; the width of a varchar column is only one example.
#
#   DATABASE_URL=postgres://user:password@host:5432/dbname
#
# A password with @ or / in it must be percent encoded, or the URL parses into
# the wrong pieces.
DATABASE_URL = os.environ.get('DATABASE_URL', '')

if not DATABASE_URL:
    raise ImproperlyConfigured(
        'DATABASE_URL is not set. This project runs on Postgres; put the '
        'address in .env, for example '
        'DATABASE_URL=postgres://user:password@127.0.0.1:5432/dup'
    )

DATABASES = {'default': database_from_url(DATABASE_URL)}


