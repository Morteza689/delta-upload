def load_dotenv(path):
    """Read .env if present.

    No library: a plain KEY=VALUE file is all we need, and one less dependency
    on shared hosting is one less thing to break.

    A real environment variable always wins, so a server can override a file
    value without editing the file.
    """
    if not path.exists():
        return

    for raw in path.read_text(encoding='utf-8').splitlines():
        line = raw.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, _, value = line.partition('=')
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


